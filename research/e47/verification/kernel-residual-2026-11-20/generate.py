"""Generate untrusted integer eigenbasis witnesses for the Lean verifier."""
from itertools import product
from functools import reduce
from math import gcd, lcm
from pathlib import Path

import sympy as s

STATES = list(product(range(-2, 3), repeat=3))
INDEX = {state: i for i, state in enumerate(STATES)}
WEIGHTS = [
    (12, 3, 2, 3, 12)[a + 2]
    * (12, 3, 2, 3, 12)[b + 2]
    * (12, 3, 2, 3, 12)[c + 2]
    for a, b, c in STATES
]
SPECTRUM = (0, 2, 6, 12, 20, 30, 42)


def casimir():
    matrix = s.zeros(125)
    for col, state in enumerate(STATES):
        matrix[col, col] = 18 + 2 * sum(
            state[i] * state[j] for i in range(3) for j in range(i + 1, 3)
        )
        for i, j in product(range(3), repeat=2):
            if i == j or state[i] == 2 or state[j] == -2:
                continue
            target = list(state)
            target[i] += 1
            target[j] -= 1
            matrix[INDEX[tuple(target)], col] += (2 - state[i]) * (2 + state[j])
    return matrix


def eigenbasis():
    matrix = casimir()
    columns, eigenvalues, norms = [], [], []
    for eigenvalue in SPECTRUM:
        for magnetization in range(-6, 7):
            block = [i for i, state in enumerate(STATES) if sum(state) == magnetization]
            metric = s.diag(*(WEIGHTS[i] for i in block))
            basis = []
            for vector in (matrix.extract(block, block) - eigenvalue * s.eye(len(block))).nullspace():
                for previous, norm in basis:
                    vector -= previous * ((previous.T * metric * vector)[0] / norm)
                vector *= lcm(*(entry.q for entry in vector))
                vector /= reduce(gcd, map(int, vector))
                norm = int((vector.T * metric * vector)[0])
                basis.append((vector, norm))
                entries = dict(zip(block, map(int, vector)))
                columns.append([entries.get(i, 0) for i in range(125)])
                eigenvalues.append(eigenvalue)
                norms.append(norm)
    return columns, eigenvalues, norms


def lean_array(values):
    return 'decode "' + " ".join(map(str, values)) + '"'


def main():
    columns, eigenvalues, norms = eigenbasis()
    lines = [
        "/- Generated by generate.py. All claims about these data are checked in Certificate.lean. -/",
        "namespace E47",
        "set_option maxHeartbeats 0",
        "set_option maxRecDepth 4096",
        'def decode (s : String) : Array Int := (s.splitOn " ").map (fun x => x.toInt?.getD 0) |>.toArray',
        "def columns : Array (Array Int) := #[",
        ",\n".join("  " + lean_array(column) for column in columns),
        "]",
        "def eigenvalues : Array Int := " + lean_array(eigenvalues),
        "def norms : Array Int := " + lean_array(norms),
        "end E47",
    ]
    Path("Witness.lean").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
